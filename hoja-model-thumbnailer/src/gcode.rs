//! The picture a slicer embeds in G-code.
//!
//! PrusaSlicer, SuperSlicer, Orca and Bambu Studio write it as comment lines
//! at the top of the file, before the first move:
//!
//! ```text
//! ; thumbnail begin 300x300 12345
//! ; iVBORw0KGgoAAAANSUhEUgAAASwAAAEsCAYAAAB5fY51AAAgAElEQVR4nO...
//! ; thumbnail end
//! ```
//!
//! `thumbnail_JPG` and `thumbnail_QOI` blocks are the same with another
//! format inside. A file can hold several sizes. The largest one is used.

use std::io::BufRead as _;
use std::path::Path;

use base64::Engine as _;

use crate::Error;

/// Never read further than this looking for a picture. Slicers write the
/// pictures first, so a file with none is given up on at its first command,
/// well before this.
const LIMIT: u64 = 8 << 20;

pub fn picture(path: &Path) -> Result<image::DynamicImage, Error> {
    let file = std::fs::File::open(path)?;
    let reader = std::io::BufReader::new(std::io::Read::take(file, LIMIT));
    let block = largest(reader.lines().map_while(Result::ok)).ok_or("no picture in the G-code")?;
    let bytes = base64::engine::general_purpose::STANDARD.decode(block.data)?;
    Ok(image::load_from_memory(&bytes)?)
}

#[derive(Debug, PartialEq)]
struct Block {
    pixels: u64,
    data: String,
}

/// The largest picture block in `lines`, read up to the first command.
fn largest(lines: impl Iterator<Item = String>) -> Option<Block> {
    let mut best: Option<Block> = None;
    let mut open: Option<Block> = None;
    for line in lines {
        let line = line.trim();
        let Some(comment) = line.strip_prefix(';') else {
            // A command: the header is over, and the pictures with it.
            if !line.is_empty() && open.is_none() {
                break;
            }
            continue;
        };
        let comment = comment.trim();
        let mut words = comment.split_ascii_whitespace();
        let (first, second) = (words.next(), words.next());
        let is_tag = first.is_some_and(|w| w == "thumbnail" || w.starts_with("thumbnail_"));
        match (is_tag, second) {
            (true, Some("begin")) => {
                let pixels = words
                    .next()
                    .and_then(|size| size.split_once('x'))
                    .and_then(|(w, h)| Some(w.parse::<u64>().ok()? * h.parse::<u64>().ok()?))
                    .unwrap_or(0);
                open = Some(Block {
                    pixels,
                    data: String::new(),
                });
            }
            (true, Some("end")) => {
                if let Some(block) = open.take()
                    && !block.data.is_empty()
                    && best.as_ref().is_none_or(|b| block.pixels > b.pixels)
                {
                    best = Some(block);
                }
            }
            _ => {
                if let Some(block) = &mut open {
                    block.data.push_str(comment);
                }
            }
        }
    }
    best
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lines(text: &str) -> impl Iterator<Item = String> + '_ {
        text.lines().map(String::from)
    }

    #[test]
    fn the_largest_picture_is_taken() {
        let text = "; generated by PrusaSlicer\n\
                    ;\n\
                    ; thumbnail begin 16x16 8\n\
                    ; c21hbGw=\n\
                    ; thumbnail end\n\
                    ; thumbnail_JPG begin 300x300 12\n\
                    ; YmlnIGJp\n\
                    ; ZyBiaWc=\n\
                    ; thumbnail_JPG end\n\
                    G28\n";
        let block = largest(lines(text)).unwrap();
        assert_eq!(block.pixels, 90_000);
        assert_eq!(block.data, "YmlnIGJpZyBiaWc=");
    }

    #[test]
    fn the_search_stops_at_the_first_command() {
        let text = "; header\nG28\n; thumbnail begin 16x16 8\n; c21hbGw=\n; thumbnail end\n";
        assert_eq!(largest(lines(text)), None);
    }

    #[test]
    fn a_real_picture_decodes() {
        let mut png = Vec::new();
        image::RgbaImage::from_pixel(4, 3, image::Rgba([255, 0, 0, 255]))
            .write_to(&mut std::io::Cursor::new(&mut png), image::ImageFormat::Png)
            .unwrap();
        let data = base64::engine::general_purpose::STANDARD.encode(&png);
        let mut text = String::from("; thumbnail begin 4x3 0\n");
        for chunk in data.as_bytes().chunks(78) {
            text.push_str("; ");
            text.push_str(std::str::from_utf8(chunk).unwrap());
            text.push('\n');
        }
        text.push_str("; thumbnail end\nG28\n");
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("part.gcode");
        std::fs::write(&path, text).unwrap();
        let picture = picture(&path).unwrap();
        assert_eq!((picture.width(), picture.height()), (4, 3));
    }
}
